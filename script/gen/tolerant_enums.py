#!/usr/bin/env python3
"""
Make the generated enum classes tolerate wire values they do not know yet.

The daemon may add a member to any enum in an *additive* minor release —
a new device kind, a new readiness phase. A client generated against the
previous contract passes the version gate, then raises `ValidationError`
the first time such a value appears in a response, because a Python enum
rejects an unseen value. An additive daemon change must not break an
already-installed client.

The fix is the enum machinery's own escape hatch: `_missing_` mints a
pseudo-member carrying the raw string, so parsing succeeds and the value
round-trips unchanged. Rather than repeat that classmethod in ~75
generated classes, this script injects one tolerant base class per base
spelling it finds and re-points every generated enum at it — an enum
without members may be subclassed, so the rewrite is legal and the
member lists stay untouched.

Both base shapes are supported and were verified against pydantic v2:

* `StrEnum` / `str, Enum` — the pseudo-member is built with
  `str.__new__`, so it *is* a `str` and compares equal to the raw value.
* plain `Enum` — `str.__new__` is not available (the class is not a
  `str` subclass), so the pseudo-member is built with `object.__new__`.
  It parses and serialises correctly and carries the raw string in
  `.value`. Caveat: plain `Enum` compares by identity and the
  pseudo-members are deliberately not cached, so two separately parsed
  *unknown* values of a plain `Enum` are not `==` to each other. Compare
  `.value` when the enum is a plain `Enum` (in the REST surface only the
  RFC-7807 `Type` is). Known members are unaffected.

The rewrite is deterministic and idempotent: the injected block is
delimited by markers and stripped before every run, so a regeneration of
an unchanged contract produces a byte-identical file — which the
"skip when the API is unchanged" guard in the daemon-release workflow
depends on.

An enum base this script does not know (an `IntEnum`, say — an unknown
integer cannot be minted as a string) is a hard error, never a silent
skip: a tolerated-looking file with an intolerant class in it is worse
than a failed generation.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

BEGIN = "# --- BEGIN tolerant-enum support (generated by script/gen/tolerant_enums.py) ---"
END = "# --- END tolerant-enum support ---"

STR_ENUM_BASE = '''class _TolerantStrEnum(StrEnum):
    """`StrEnum` that accepts wire values this client does not know yet."""

    @classmethod
    def _missing_(cls, value: object) -> _TolerantStrEnum | None:  # kwonly: disable
        """Mint a pseudo-member carrying the raw string instead of raising."""
        if not isinstance(value, str):
            return None
        member = str.__new__(cls, value)
        member._name_ = value
        member._value_ = value
        return member'''

STR_MIXIN_BASE = '''class _TolerantStrMixinEnum(str, Enum):
    """`str`-mixin enum that accepts wire values this client does not know yet."""

    @classmethod
    def _missing_(cls, value: object) -> _TolerantStrMixinEnum | None:  # kwonly: disable
        """Mint a pseudo-member carrying the raw string instead of raising."""
        if not isinstance(value, str):
            return None
        member = str.__new__(cls, value)
        member._name_ = value
        member._value_ = value
        return member'''

PLAIN_ENUM_BASE = '''class _TolerantEnum(Enum):
    """Plain `Enum` that accepts wire values this client does not know yet.

    The class is not a `str` subclass, so the pseudo-member is built with
    `object.__new__` and carries the raw string in `.value`.
    """

    @classmethod
    def _missing_(cls, value: object) -> _TolerantEnum | None:  # kwonly: disable
        """Mint a pseudo-member carrying the raw string instead of raising."""
        if not isinstance(value, str):
            return None
        member = object.__new__(cls)
        member._name_ = value
        member._value_ = value
        return member'''

# Base spelling as the generator writes it -> (tolerant base name, its source).
# Each tolerant name maps to exactly one source, so a file this script has
# already processed can be recognised and reproduced byte-for-byte.
KNOWN_BASES: dict[str, tuple[str, str]] = {
    "StrEnum": ("_TolerantStrEnum", STR_ENUM_BASE),
    "str, Enum": ("_TolerantStrMixinEnum", STR_MIXIN_BASE),
    "Enum": ("_TolerantEnum", PLAIN_ENUM_BASE),
}
TOLERANT_BASES: dict[str, str] = dict(KNOWN_BASES.values())

CLASS_RE = re.compile(r"^class (?P<name>\w+)\((?P<bases>[^)]*)\):$", re.MULTILINE)
# Substring, not `\bEnum\b`: the generated bases are spelled `StrEnum` and
# `str, Enum`, and a word-boundary match silently skips the former — which is
# 74 of the 75 generated classes.
ENUM_BASE_RE = re.compile(r"Enum|Flag")
BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n*", re.DOTALL)


def strip_block(text: str) -> str:
    """Remove a previously injected block so the rewrite is idempotent."""
    return BLOCK_RE.sub("", text)


def rewrite(text: str, path: Path) -> tuple[str, int]:
    """
    Re-point every generated enum class at a tolerant base.

    Returns the new text and the number of classes rewritten. Raises
    `ValueError` for an enum base this script cannot make tolerant.
    """
    text = strip_block(text)

    needed: list[str] = []
    count = 0

    def repl(m: re.Match[str]) -> str:
        nonlocal count
        bases = ", ".join(part.strip() for part in m["bases"].split(","))
        if not ENUM_BASE_RE.search(bases):
            return m[0]
        if bases in TOLERANT_BASES:
            # Already processed (the block above was stripped): keep the class
            # as it is, but re-request its base so the block is rebuilt.
            source = TOLERANT_BASES[bases]
            if source not in needed:
                needed.append(source)
            count += 1
            return m[0]
        if bases not in KNOWN_BASES:
            raise ValueError(
                f"{path}: class {m['name']}({bases}) is an enum with a base this "
                f"script cannot make tolerant. Extend KNOWN_BASES in "
                f"script/gen/tolerant_enums.py — do not skip it, or that enum "
                f"still raises on an unknown daemon value."
            )
        tolerant, source = KNOWN_BASES[bases]
        if source not in needed:
            needed.append(source)
        count += 1
        return f"class {m['name']}({tolerant}):"

    body = CLASS_RE.sub(repl, text)
    if not count:
        return body, 0

    first = CLASS_RE.search(body)
    if first is None:  # pragma: no cover - unreachable while count > 0
        raise ValueError(f"{path}: rewrote {count} enums but found no class to anchor the block above")

    block = "\n\n\n".join([BEGIN, *needed, END])
    head = body[: first.start()].rstrip("\n")
    tail = body[first.start() :]
    return f"{head}\n\n\n{block}\n\n\n{tail}", count


def main() -> int:
    """Rewrite each given generated module in place and report the counts."""
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--py",
        required=True,
        action="append",
        type=Path,
        help="Generated module to post-process; repeatable.",
    )
    args = p.parse_args()

    for path in args.py:
        if not path.is_file():
            print(f"generated module not found: {path}", file=sys.stderr)
            return 1
        original = path.read_text()
        try:
            new, count = rewrite(original, path)
        except ValueError as err:
            print(str(err), file=sys.stderr)
            return 1
        if not count:
            print(f"{path}: no enum classes found — nothing to make tolerant")
            continue
        if new != original:
            path.write_text(new)
        print(f"{path}: {count} enum classes now tolerate unknown wire values")
    return 0


if __name__ == "__main__":
    sys.exit(main())
