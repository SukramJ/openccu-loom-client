"""
Emit the set of daemon operations this package actually calls.

Why it is published rather than merely asserted. The daemon's versioning
policy makes every removal a major bump, and the client used to refuse any
daemon whose major differed. Both rules are individually defensible and
together they locked users out: the daemon's major moved 7 -> 8 -> 9 -> 10
inside one release window, and every one of those bumps removed surface no
generated client referenced. The daemon could not know that, because nothing
told it what a client consumes.

This writes that down. ``spec/consumed_operations.json`` is read by the
daemon's own surface guard (``tests/contract/api_surface_bump_test.go``) when
this repository is checked out beside it, so a removal can be classified
against what is actually consumed instead of against the whole document.

The extraction is the same AST walk the operations contract test runs, and
that test imports it from here: one implementation, so the published set
cannot drift from the asserted one.

Usage:
    python3 script/gen/consumed_operations.py [--check]

``--check`` verifies the committed file is current without rewriting it,
which is what CI runs.
"""

from __future__ import annotations

import argparse
import ast
import json
import pathlib
import re
import sys

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
OPERATIONS_DIR = _REPO_ROOT / "openccu_loom_client" / "operations"
MANIFEST_PATH = _REPO_ROOT / "spec" / "consumed_operations.json"

# The request helpers every façade routes through. `_base.py` is excluded from
# the walk: its `_request_list` forwards a `path` parameter it was handed, so
# it is plumbing rather than a call site.
REQUEST_HELPERS = frozenset({"request", "_request_list"})

# Call sites outside operations/ that are nonetheless part of the contract this
# package depends on. `GET /info` is the handshake itself — connect() issues it
# from transport/http.py before any façade exists — so it is the one operation
# whose removal would break this client absolutely, and the AST walk below
# cannot see it.
EXTRA_OPERATIONS = ("GET /info",)


def normalise(path: str) -> str:
    """
    Reduce a path to its shape, with every parameter as ``{}``.

    Parameter *names* are not part of the wire contract — the daemon calls one
    ``{channel_no}`` where this package calls it ``{channel}`` — so comparing
    them would report a difference that does not exist. The daemon side
    normalises identically before comparing.
    """
    return re.sub(r"\{[^{}]*\}", "{}", path)


def literal_path(node: ast.AST) -> str | None:
    """Return the path a ``path=`` argument builds, or ``None`` if it is not static."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return "".join(str(v.value) if isinstance(v, ast.Constant) else "{}" for v in node.values)
    return None


def client_calls() -> dict[tuple[str, str], list[str]]:
    """Return ``{(method, path shape): [source locations]}`` for every façade call."""
    calls: dict[tuple[str, str], list[str]] = {}
    for source in sorted(OPERATIONS_DIR.glob("*.py")):
        if source.name in ("_base.py", "__init__.py"):
            continue
        for node in ast.walk(ast.parse(source.read_text(encoding="utf-8"))):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)):
                continue
            if node.func.attr not in REQUEST_HELPERS:
                continue
            kwargs = {kw.arg: kw.value for kw in node.keywords}
            method_node, path_node = kwargs.get("method"), kwargs.get("path")
            if not (isinstance(method_node, ast.Constant) and isinstance(method_node.value, str)):
                continue
            if path_node is None or (path := literal_path(path_node)) is None:
                continue
            calls.setdefault((method_node.value.upper(), normalise(path)), []).append(f"{source.name}:{node.lineno}")
    return calls


def build_manifest() -> dict[str, object]:
    """Return the manifest document: a sorted, de-duplicated operation list."""
    operations = {f"{method} {path}" for method, path in client_calls()}
    operations.update(EXTRA_OPERATIONS)
    return {
        "description": (
            "Daemon operations openccu-loom-client calls, as 'METHOD path-shape' with every path "
            "parameter reduced to {}. Generated by script/gen/consumed_operations.py from an AST "
            "walk of openccu_loom_client/operations/, plus the handshake call in transport/http.py. "
            "Read by the daemon's api_surface_bump_test.go to tell a removal this client would "
            "notice from one it would not."
        ),
        "client_version": _client_version(),
        "operations": sorted(operations),
    }


def _client_version() -> str:
    """Return this package's version without importing it (no runtime deps at gen time)."""
    const = _REPO_ROOT / "openccu_loom_client" / "const.py"
    for line in const.read_text(encoding="utf-8").splitlines():
        if line.startswith("VERSION"):
            _, _, value = line.partition("=")
            return value.strip().strip('"').strip("'")
    return "unknown"


def main(argv: list[str] | None = None) -> int:
    """Write the manifest, or verify the committed one is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed manifest is stale")
    args = parser.parse_args(argv)

    manifest = build_manifest()
    if not manifest["operations"]:
        print("extracted no operations — the AST walk stopped matching", file=sys.stderr)
        return 2
    rendered = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"

    if args.check:
        if not MANIFEST_PATH.is_file():
            print(f"{MANIFEST_PATH} is missing — run script/gen/consumed_operations.py", file=sys.stderr)
            return 1
        if MANIFEST_PATH.read_text(encoding="utf-8") != rendered:
            print(f"{MANIFEST_PATH} is stale — run script/gen/consumed_operations.py", file=sys.stderr)
            return 1
        return 0

    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {MANIFEST_PATH} with {len(manifest['operations'])} operations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
